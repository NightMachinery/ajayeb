func catalogTSOrFail(t *testing.T) string {
	t.Helper()
	data, err := catalogTS()
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

// tsEntries reads back the `'slug': {json},` lines of one exported object.
func tsEntries(t *testing.T, src, object string) map[string]json.RawMessage {
	t.Helper()
	start := strings.Index(src, "export const "+object+": ")
	if start < 0 {
		t.Fatalf("no export const %s", object)
	}
	body := src[start:]
	end := strings.Index(body, "\n};\n")
	if end < 0 {
		t.Fatalf("export const %s is not closed", object)
	}
	line := regexp.MustCompile(`^  '([a-z0-9-]+)': (\{.*\}),$`)
	out := map[string]json.RawMessage{}
	for _, l := range strings.Split(body[:end], "\n")[1:] {
		m := line.FindStringSubmatch(l)
		if m == nil {
			t.Fatalf("%s: unexpected line %q", object, l)
		}
		if _, dup := out[m[1]]; dup {
			t.Fatalf("%s: slug %s twice", object, m[1])
		}
		out[m[1]] = json.RawMessage(m[2])
	}
	return out
}

func TestCatalogTSHoldsTheJSONCatalog(t *testing.T) {
	src := catalogTSOrFail(t)
	cat := buildCatalog()

	cards := tsEntries(t, src, "cards")
	if len(cards) != len(cat.Cards) || len(cards) != 73 {
		t.Fatalf("cards: %d entries, catalog has %d", len(cards), len(cat.Cards))
	}
	for _, want := range cat.Cards {
		var got jsonCard
		if err := json.Unmarshal(cards[want.Slug], &got); err != nil {
			t.Fatalf("%s: %v", want.Slug, err)
		}
		g, _ := json.Marshal(got)
		w, _ := json.Marshal(want)
		if !bytes.Equal(g, w) {
			t.Errorf("card %s:\n got %s\nwant %s", want.Slug, g, w)
		}
	}

	wonders := tsEntries(t, src, "wonders")
	if len(wonders) != len(cat.Wonders) || len(wonders) != 12 {
		t.Fatalf("wonders: %d entries, catalog has %d", len(wonders), len(cat.Wonders))
	}
	for _, want := range cat.Wonders {
		var got jsonWonder
		if err := json.Unmarshal(wonders[want.Slug], &got); err != nil {
			t.Fatalf("%s: %v", want.Slug, err)
		}
		g, _ := json.Marshal(got)
		w, _ := json.Marshal(want)
		if !bytes.Equal(g, w) {
			t.Errorf("wonder %s:\n got %s\nwant %s", want.Slug, g, w)
		}
	}

	tokens := tsEntries(t, src, "tokens")
	if len(tokens) != len(cat.Tokens) || len(tokens) != 10 {
		t.Fatalf("tokens: %d entries, catalog has %d", len(tokens), len(cat.Tokens))
	}
	for _, want := range cat.Tokens {
		var got jsonToken
		if err := json.Unmarshal(tokens[want.Slug], &got); err != nil {
			t.Fatalf("%s: %v", want.Slug, err)
		}
		g, _ := json.Marshal(got)
		w, _ := json.Marshal(want)
		if !bytes.Equal(g, w) {
			t.Errorf("token %s:\n got %s\nwant %s", want.Slug, g, w)
		}
	}
}

func TestCatalogTSHashAndSlugLists(t *testing.T) {
	src := catalogTSOrFail(t)
	h := engine.CatalogHash()
	if !strings.Contains(src, "export const catalogHash = '"+h+"';\n") {
		t.Errorf("catalog.gen.ts does not carry engine.CatalogHash() %s", h)
	}
	cat := buildCatalog()
	var b strings.Builder
	slugList(&b, "cardSlugs", func() []string {
		s := make([]string, len(cat.Cards))
		for i, c := range cat.Cards {
			s[i] = c.Slug
		}
		return s
	}())
	if !strings.Contains(src, b.String()) {
		t.Error("cardSlugs is not every card slug in id order")
	}
	for _, kind := range effectKindNames() {
		if !strings.Contains(src, "'"+kind+"'") {
			t.Errorf("EffectKind lacks %q", kind)
		}
	}
	if strings.Contains(src, "'none'") {
		t.Error("EffectKind includes the zero kind none")
	}
	// Every effect kind the data uses is in the union.
	used := regexp.MustCompile(`"kind":"([a-z-]+)"`).FindAllStringSubmatch(src, -1)
	if len(used) == 0 {
		t.Fatal("no effects found")
	}
	union := src[strings.Index(src, "export type EffectKind"):]
	union = union[:strings.Index(union, "\n")]
	for _, m := range used {
		if !strings.Contains(union, "'"+m[1]+"'") {
			t.Errorf("effect kind %q is used but not in EffectKind", m[1])
		}
	}
}

func TestCatalogTSDeterministicAndBalanced(t *testing.T) {
	a := catalogTSOrFail(t)
	b := catalogTSOrFail(t)
	if a != b {
		t.Fatal("two runs differ")
	}
	if o, c := strings.Count(a, "{"), strings.Count(a, "}"); o != c {
		t.Errorf("unbalanced braces: %d { vs %d }", o, c)
	}
	if o, c := strings.Count(a, "["), strings.Count(a, "]"); o != c {
		t.Errorf("unbalanced brackets: %d [ vs %d ]", o, c)
	}
	if !strings.HasPrefix(a, "// Code generated by ajayeb-gen. DO NOT EDIT.\n") || !strings.HasSuffix(a, "};\n") {
		t.Error("missing the generated header or the final newline")
	}
}

// TestCatalogTSCommitted fails when the catalog changed but make gen was not
// run; make gen-check catches the same thing for the whole directory.
func TestCatalogTSCommitted(t *testing.T) {
	got, err := os.ReadFile(committedCatalogTS)
	if err != nil {
		t.Skipf("no committed catalog.gen.ts to compare (%v)", err)
	}
	if string(got) != catalogTSOrFail(t) {
		t.Error("web/src/lib/wire/catalog.gen.ts is stale: run make gen")
	}
}

func TestCatalogFormatTS(t *testing.T) {
	stdout, _ := runOK(t, "catalog", "-format", "ts")
	if stdout != catalogTSOrFail(t) {
		t.Error("catalog -format ts differs from catalogTS()")
	}
	dir := t.TempDir()
	runOK(t, "catalog", "-format", "ts", "-out", dir)
	if entries, _ := os.ReadDir(dir); len(entries) != 1 || entries[0].Name() != "catalog.gen.ts" {
		t.Errorf("-format ts -out wrote %v", entries)
	}
}

func TestDefaultRunWritesBothFiles(t *testing.T) {
	dir := t.TempDir()
	p := genPaths{
		fixturesOut: filepath.Join(dir, "a", "fixtures.gen.ts"),
		catalogOut:  filepath.Join(dir, "a", "catalog.gen.ts"),
		messagesDir: messagesDir,
		protocolDir: protocolDir,
	}
	var out bytes.Buffer
	if err := runDefault(&out, p); err != nil {
		t.Fatal(err)
	}
	for _, f := range []string{p.fixturesOut, p.catalogOut} {
		if _, err := os.Stat(f); err != nil {
			t.Error(err)
		}
		if !strings.Contains(out.String(), "wrote "+f) {
			t.Errorf("stdout %q does not mention %s", out.String(), f)
		}
	}
	// A second run leaves an identical catalog file alone.
	before, _ := os.Stat(p.catalogOut)
	if err := runDefault(&out, p); err != nil {
		t.Fatal(err)
	}
	after, _ := os.Stat(p.catalogOut)
	if !before.ModTime().Equal(after.ModTime()) {
		t.Error("an unchanged catalog.gen.ts was rewritten")
	}
}

func TestFixtureNames(t *testing.T) {
	out := filepath.Join(t.TempDir(), "fixtures.gen.ts")
	if err := generateFixtures(out, messagesDir, protocolDir); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	src := string(data)
	for _, want := range []string{
		"export const fixtureNames = [\n",
		`  "state-play",` + "\n",
		"export const protocolFixtureNames = [\n",
		`  "age-1-start-seat0",` + "\n",
		`  "age-1-start-spectator",` + "\n",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("fixtures.gen.ts lacks %q", want)
		}
	}
	names, _, err := readJSONFiles(messagesDir)
	if err != nil {
		t.Fatal(err)
	}
	viewNames, views, err := readProtocolViews(protocolDir)
	if err != nil {
		t.Fatal(err)
	}
	if len(viewNames) != len(views) {
		t.Fatalf("%d names for %d views", len(viewNames), len(views))
	}
	list := src[strings.Index(src, "export const fixtureNames"):]
	if n := strings.Count(list[:strings.Index(list, "] as const;")], "\n  \""); n != len(names) {
		t.Errorf("fixtureNames has %d entries, want %d", n, len(names))
	}
	list = src[strings.Index(src, "export const protocolFixtureNames"):]
	if n := strings.Count(list[:strings.Index(list, "] as const;")], "\n  \""); n != len(views) {
		t.Errorf("protocolFixtureNames has %d entries, want %d", n, len(views))
	}
}

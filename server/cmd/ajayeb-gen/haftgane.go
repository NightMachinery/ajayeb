package main

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"

	haftganecatalog "github.com/NightMachinery/ajayeb/server/internal/haftgane/catalog"
)

// Haftgane's catalog dumps: the record tables (csv), the prose review text
// and the client's presentation catalog (ts, haftganets.go). json is Duel's
// only.
var (
	haftganeFormats = []string{"csv", "prose", "ts"}
	haftganeTables  = []string{"cards", "wonders", "boards"}
)

// haftganeOutputs renders the files the options ask for, in a fixed order.
func haftganeOutputs(o catalogOptions) ([]output, error) {
	switch o.format {
	case "csv":
		tbls, err := haftganecatalog.RecordTables()
		if err != nil {
			return nil, err
		}
		var outs []output
		for _, t := range tbls {
			if o.table != "" && t.Name != o.table {
				continue
			}
			var buf bytes.Buffer
			if err := t.WriteCSV(&buf); err != nil {
				return nil, err
			}
			outs = append(outs, output{t.Name + ".csv", buf.Bytes()})
		}
		return outs, nil
	case "prose":
		return []output{{"catalog.txt", haftganeProse()}}, nil
	case "ts":
		data, err := haftganeCatalogTS()
		if err != nil {
			return nil, err
		}
		return []output{{"haftgane-catalog.gen.ts", data}}, nil
	}
	return nil, fmt.Errorf("format %q is not available for haftgane", o.format)
}

// haftganeProse writes every design and wonder stage with each effect in
// plain English, for a semantic review of the data against
// docs/haftgane/rules.md.
func haftganeProse() []byte {
	var b bytes.Buffer
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	p("Haftgane catalog in plain English: every card design and wonder stage, one line per effect.\n")
	p("Generated by ajayeb-gen catalog -game haftgane -format prose from the engine catalog; do not edit.\n")

	p("\nCARD DESIGNS\n")
	for id := haftganecatalog.DesignID(1); id <= haftganecatalog.NumDesigns; id++ {
		d, ok := haftganecatalog.DesignByID(id)
		if !ok {
			continue
		}
		kind := "card, " + copiesProse(d.Copies)
		if d.Color == haftganecatalog.Purple {
			kind = "guild (N + 2 of the 10 guilds are drawn for N players)"
		}
		p("\n%d. %s (%s): Age %s %s %s. Cost: %s.\n", d.ID, d.Name, d.Slug, romanAge(d.Age), d.Color, kind, haftganeCostProse(d.Cost))
		for _, e := range d.Effects {
			p("   - %s\n", haftganeEffectProse(e, d.Color))
		}
		if twin := haftganecatalog.Twin[id]; twin != 0 {
			o, _ := haftganecatalog.DesignByID(twin)
			p("   - Shares its name with the Age %s %s: a city that holds either may not construct the other.\n", romanAge(o.Age), o.Name)
		}
		if d.ChainIn != 0 {
			var from []string
			for _, pid := range haftganecatalog.T.ChainProviders[d.ChainIn] {
				if pd, ok := haftganecatalog.DesignByID(pid); ok {
					from = append(from, pd.Name)
				}
			}
			p("   - Free to construct if you already own %s, which shows chain symbol %d.\n", joinList(from, "or"), d.ChainIn)
		}
		for _, c := range d.ChainOut {
			if c == 0 {
				continue
			}
			to, _ := haftganecatalog.DesignByID(haftganecatalog.T.ChainTarget[c])
			p("   - Shows chain symbol %d, which makes %s free to construct later.\n", c, to.Name)
		}
	}

	p("\nWONDER BOARDS\n")
	for id := haftganecatalog.BoardID(1); id <= haftganecatalog.NumBoards; id++ {
		bd, ok := haftganecatalog.BoardByID(id)
		if !ok {
			continue
		}
		p("\n%d. %s, %s (%s). Produces 1 %s every turn from the start, which neighbours may buy.\n", bd.ID, bd.Name, bd.Wonder, bd.Slug, bd.Start)
		for side, def := range bd.Sides {
			name := haftganecatalog.Side(side + 1).String()
			for i := range def.NumStages {
				st := def.Stages[i]
				var fx []string
				for _, e := range st.Effects {
					fx = append(fx, haftganeEffectProse(e, haftganecatalog.NoColor))
				}
				p("   - %s side, stage %d of %d. Cost: %s. %s\n", strings.ToUpper(name[:1])+name[1:], i+1, def.NumStages, haftganeCostProse(st.Cost), strings.Join(fx, " "))
			}
		}
	}
	return b.Bytes()
}

// copiesProse writes the copy markers: "one copy, from 3 players" or "two
// copies, from 3 and 6 players".
func copiesProse(markers [3]uint8) string {
	var ms []string
	for _, m := range markers {
		if m != 0 {
			ms = append(ms, strconv.Itoa(int(m)))
		}
	}
	count := [...]string{"no copies", "one copy", "two copies", "three copies"}[len(ms)]
	return count + ", from " + joinList(ms, "and") + " players"
}

func haftganeCostProse(c haftganecatalog.Cost) string {
	var parts []string
	if c.Coins > 0 {
		parts = append(parts, plural(c.Coins, "coin", "coins"))
	}
	for r := range haftganecatalog.NumResources {
		if n := c.Res[r]; n > 0 {
			parts = append(parts, strconv.Itoa(int(n))+" "+r.String())
		}
	}
	if len(parts) == 0 {
		return "free"
	}
	return joinList(parts, "and")
}

func haftganeResources(m haftganecatalog.ResMask) []string {
	var out []string
	for r := range haftganecatalog.NumResources {
		if m.Has(r) {
			out = append(out, r.String())
		}
	}
	return out
}

// haftganeCities names the cities a counting effect sums over.
func haftganeCities(s haftganecatalog.SeatScope) string {
	switch s {
	case haftganecatalog.Self:
		return "your city"
	case haftganecatalog.Left | haftganecatalog.Right:
		return "your two neighbours' cities"
	case haftganecatalog.Self | haftganecatalog.Left | haftganecatalog.Right:
		return "your city and your two neighbours' cities"
	}
	return "an unknown set of cities"
}

// haftganeCounted describes the cards a per-card effect counts.
func haftganeCounted(e haftganecatalog.Effect, own haftganecatalog.Color) string {
	var each []string
	for c := haftganecatalog.Brown; c < haftganecatalog.NumColors; c++ {
		if e.Colors.Has(c) {
			each = append(each, "each "+c.String())
		}
	}
	s := joinList(each, "and") + " card in " + haftganeCities(e.Scope)
	if e.Scope&haftganecatalog.Self != 0 && e.Colors.Has(own) {
		s += ", this card included"
	}
	return s
}

// haftganeEffectProse renders one effect as a sentence. own is the colour of
// the card carrying it (NoColor for a wonder stage).
func haftganeEffectProse(e haftganecatalog.Effect, own haftganecatalog.Color) string {
	sale := " Neighbours may not buy it."
	if e.ForSale {
		sale = " Neighbours may buy it."
	}
	switch e.Kind {
	case haftganecatalog.EffProduce:
		return fmt.Sprintf("Produces %d %s every turn.%s", e.N, e.Res, sale)
	case haftganecatalog.EffProduceChoice:
		return fmt.Sprintf("Produces 1 unit of your choice of %s every turn.%s", joinList(haftganeResources(e.Mask), "or"), sale)
	case haftganecatalog.EffTradeDiscount:
		from := "either neighbour"
		switch e.Scope {
		case haftganecatalog.Left:
			from = "your left neighbour"
		case haftganecatalog.Right:
			from = "your right neighbour"
		}
		return fmt.Sprintf("You buy %s from %s at %s per unit instead of 2.", joinList(haftganeResources(e.Mask), "and"), from, plural(e.N, "coin", "coins"))
	case haftganecatalog.EffShields:
		return fmt.Sprintf("%s of military strength.", plural(e.N, "shield", "shields"))
	case haftganecatalog.EffScience:
		return fmt.Sprintf("Shows the %s science symbol.", e.Symbol)
	case haftganecatalog.EffScienceChoice:
		return "Counts as one science symbol of your choice (compass, gear or tablet), chosen when the game is scored."
	case haftganecatalog.EffCoins:
		return fmt.Sprintf("You gain %s once, when it is placed.", plural(e.N, "coin", "coins"))
	case haftganecatalog.EffCoinsPerCard:
		return fmt.Sprintf("Once, when placed: you gain %s for %s.", plural(e.N, "coin", "coins"), haftganeCounted(e, own))
	case haftganecatalog.EffCoinsPerStage:
		return fmt.Sprintf("Once, when placed: you gain %s for each wonder stage built in %s.", plural(e.N, "coin", "coins"), haftganeCities(e.Scope))
	case haftganecatalog.EffPoints:
		return fmt.Sprintf("Worth %s at the end of the game.", plural(e.N, "victory point", "victory points"))
	case haftganecatalog.EffPointsPerCard:
		return fmt.Sprintf("At the end of the game: worth %s for %s.", plural(e.N, "victory point", "victory points"), haftganeCounted(e, own))
	case haftganecatalog.EffPointsPerStage:
		return fmt.Sprintf("At the end of the game: worth %s for each wonder stage built in %s.", plural(e.N, "victory point", "victory points"), haftganeCities(e.Scope))
	case haftganecatalog.EffPointsIfWonderComplete:
		return fmt.Sprintf("At the end of the game: worth %s if every stage of your wonder side is built.", plural(e.N, "victory point", "victory points"))
	case haftganecatalog.EffPlayLastCard:
		return "From this Age on, you keep the card left over on the sixth turn and play it as an extra turn after everyone's sixth card."
	case haftganecatalog.EffBuildFromDiscard:
		return "At the end of the turn this stage is built, you look through the discard pile and may construct one card from it for free."
	case haftganecatalog.EffFreeBuild:
		switch e.When {
		case haftganecatalog.FirstOfColour:
			return "Constructing a building of a colour not yet in your city is free."
		case haftganecatalog.FirstTurnOfAge:
			return "The building you construct on the first turn of each Age is free."
		case haftganecatalog.LastTurnOfAge:
			return "The building you construct on the sixth turn of each Age is free."
		}
	}
	return "Unknown effect " + e.Kind.String() + "."
}

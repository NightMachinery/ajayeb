// This file is the fixtures subcommand: it turns real server output,
// recorded on disk by two different Go tests, into one TypeScript file that
// svelte-check type-checks against the generated wire types (make
// check-web), so a shape the server actually sends -- not a hand-written
// example -- validates the client's types.
//
//   - internal/wire/testdata/messages/*.json: whole ServerMessage frames,
//     recorded by internal/wire's TestRecordMessages (go test ./internal/wire
//     -run TestRecordMessages -update).
//   - internal/engine/testdata/protocol/*.json: named scenarios, each with
//     one View per viewer, recorded by internal/engine's view tests. Only
//     the View objects are used here; the scenario's name and prose
//     description are not wire data.
//
// Both are read as already-valid JSON text and spliced into the output
// almost verbatim (re-indented, for the protocol fixtures, since their own
// pretty-printing is not this package's concern), rather than decoded into
// Go structs and re-marshaled: that would risk silently reshaping a field
// this generator does not know about, defeating the point of validating
// real server output.
//
// defaultMessagesDir, defaultProtocolDir and defaultFixturesOut are
// relative to server/, the working directory make gen runs this command
// from (`go -C server run ./cmd/ajayeb-gen`, same as tygo); pass -messages,
// -protocol and -out to run it from elsewhere.
const (
	defaultMessagesDir = "internal/wire/testdata/messages"
	defaultProtocolDir = "internal/engine/testdata/protocol"
	defaultFixturesOut = "../web/src/lib/wire/fixtures.gen.ts"
)

// generateFixtures reads every recorded message and every protocol
// scenario's views and writes the combined TypeScript fixture file to out
// (its directory is created if needed).
func generateFixtures(out, messagesDir, protocolDir string) error {
	messageNames, messages, err := readJSONFiles(messagesDir)
	if err != nil {
		return fmt.Errorf("reading recorded messages: %w", err)
	}
	if len(messages) == 0 {
		return fmt.Errorf("no recorded messages found under %s", messagesDir)
	}
	viewNames, views, err := readProtocolViews(protocolDir)
	if err != nil {
		return fmt.Errorf("reading protocol fixtures: %w", err)
	}
	if len(views) == 0 {
		return fmt.Errorf("no protocol fixtures found under %s", protocolDir)
	}

	var b strings.Builder
	b.WriteString("// Code generated by `ajayeb-gen fixtures`. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// fixtures are real server frames, recorded from the engine and wire packages\n")
	b.WriteString("// by internal/wire's TestRecordMessages (server/internal/wire/testdata/messages/*.json).\n")
	b.WriteString("// protocolFixtures are real View snapshots from internal/engine's own protocol\n")
	b.WriteString("// scenarios (server/internal/engine/testdata/protocol/*.json), one per viewer. Both are\n")
	b.WriteString("// `satisfies` assertions: svelte-check fails here, not at runtime, the moment a\n")
	b.WriteString("// real server shape (a null where a slice must be [], a renamed field, a changed\n")
	b.WriteString("// enum string) no longer fits the generated TypeScript (make check-web).\n")
	b.WriteString("import type { ServerMessage } from './index';\n")
	b.WriteString("import type { View } from './view.gen';\n\n")

	b.WriteString("export const fixtures = [\n")
	for i, m := range messages {
		if i > 0 {
			b.WriteString(",\n")
		}
		b.WriteString(indentBlock(m, "  "))
	}
	b.WriteString("\n] satisfies ServerMessage[];\n\n")

	b.WriteString("export const protocolFixtures = [\n")
	for i, v := range views {
		if i > 0 {
			b.WriteString(",\n")
		}
		b.WriteString(indentBlock(v, "  "))
	}
	b.WriteString("\n] satisfies View[];\n\n")

	b.WriteString("/** fixtureNames[i] names fixtures[i]: its recorded file's name without .json. */\n")
	writeNameList(&b, "fixtureNames", messageNames)
	b.WriteString("\n/** protocolFixtureNames[i] names protocolFixtures[i]: the scenario file and the viewer, as in age-1-start.seat0. */\n")
	writeNameList(&b, "protocolFixtureNames", viewNames)

	if dir := filepath.Dir(out); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	return os.WriteFile(out, []byte(b.String()), 0o644)
}

// writeNameList writes a readonly tuple of fixture names, one per line.
func writeNameList(b *strings.Builder, name string, names []string) {
	fmt.Fprintf(b, "export const %s = [\n", name)
	for _, n := range names {
		fmt.Fprintf(b, "  %q,\n", n)
	}
	b.WriteString("] as const;\n")
}

// readJSONFiles reads every *.json file in dir, sorted by name for a
// reproducible, reviewable diff, and returns each one's name without the
// extension and its content with trailing whitespace trimmed.
func readJSONFiles(dir string) (fileNames, contents []string, err error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, nil, err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() && filepath.Ext(e.Name()) == ".json" {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)
	contents = make([]string, 0, len(names))
	for _, name := range names {
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, nil, err
		}
		var probe any
		if err := json.Unmarshal(data, &probe); err != nil {
			return nil, nil, fmt.Errorf("%s: %w", name, err)
		}
		fileNames = append(fileNames, strings.TrimSuffix(name, ".json"))
		contents = append(contents, strings.TrimRight(string(data), "\n\r \t"))
	}
	return fileNames, contents, nil
}

// protocolFixtureFile is the shape internal/engine's view tests record
// under testdata/protocol: a named scenario with one View per viewer. Only
// View is wire data; name and about are the scenario's own documentation.
type protocolFixtureFile struct {
	Name    string `json:"name"`
	About   string `json:"about"`
	Viewers []struct {
		Viewer string          `json:"viewer"`
		View   json.RawMessage `json:"view"`
	} `json:"viewers"`
}

// readProtocolViews reads every viewer's View out of every scenario file in
// dir, in file and then viewer order, each re-indented to two spaces
// regardless of how the source file was printed. Each view is named
// "<file without .json>.<viewer>".
func readProtocolViews(dir string) (viewNames, views []string, err error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, nil, err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() && filepath.Ext(e.Name()) == ".json" {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)

	for _, name := range names {
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, nil, err
		}
		var f protocolFixtureFile
		if err := json.Unmarshal(data, &f); err != nil {
			return nil, nil, fmt.Errorf("%s: %w", name, err)
		}
		if len(f.Viewers) == 0 {
			return nil, nil, fmt.Errorf("%s: no viewers", name)
		}
		for _, viewer := range f.Viewers {
			pretty, err := reindent(viewer.View)
			if err != nil {
				return nil, nil, fmt.Errorf("%s (%s): %w", name, viewer.Viewer, err)
			}
			viewNames = append(viewNames, strings.TrimSuffix(name, ".json")+"."+viewer.Viewer)
			views = append(views, pretty)
		}
	}
	return viewNames, views, nil
}

// reindent re-marshals raw JSON with a consistent two-space indent,
// independent of how the source file happened to be printed.
func reindent(raw json.RawMessage) (string, error) {
	var buf bytes.Buffer
	if err := json.Indent(&buf, raw, "", "  "); err != nil {
		return "", err
	}
	return buf.String(), nil
}

// indentBlock prefixes every line of s with prefix, for nesting a
// multi-line JSON value one level deeper inside a TypeScript array literal.
func indentBlock(s, prefix string) string {
	lines := strings.Split(s, "\n")
	for i, line := range lines {
		if line == "" {
			continue
		}
		lines[i] = prefix + line
	}
	return strings.Join(lines, "\n")
}

// fixturesOptions is the parsed command line of the fixtures subcommand.
type fixturesOptions struct {
	out         string
	messagesDir string
	protocolDir string
}

func parseFixturesFlags(args []string, stderr io.Writer) (fixturesOptions, error) {
	o := fixturesOptions{}
	fs := flag.NewFlagSet("ajayeb-gen fixtures", flag.ContinueOnError)
	fs.SetOutput(stderr)
	fs.StringVar(&o.out, "out", defaultFixturesOut, "write the fixture file to this `path`")
	fs.StringVar(&o.messagesDir, "messages", defaultMessagesDir, "read recorded wire messages from this `directory`")
	fs.StringVar(&o.protocolDir, "protocol", defaultProtocolDir, "read protocol view scenarios from this `directory`")
	fs.Usage = func() {
		fmt.Fprint(stderr, "Usage: ajayeb-gen fixtures [-out PATH] [-messages DIR] [-protocol DIR]\n\n")
		fs.PrintDefaults()
	}
	if err := fs.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return o, err
		}
		return o, errUsage
	}
	if fs.NArg() > 0 {
		fmt.Fprintf(stderr, "ajayeb-gen fixtures: unexpected argument %q\n", fs.Arg(0))
		return o, errUsage
	}
	return o, nil
}

// runFixturesCmd is the fixtures subcommand's entry point.
func runFixturesCmd(args []string, stdout, stderr io.Writer) error {
	o, err := parseFixturesFlags(args, stderr)
	if err != nil {
		return err
	}
	if err := generateFixtures(o.out, o.messagesDir, o.protocolDir); err != nil {
		return err
	}
	fmt.Fprintf(stdout, "wrote %s\n", o.out)
	return nil
}

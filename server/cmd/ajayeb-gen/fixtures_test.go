package main

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// messagesDir and protocolDir are the real fixture sources, relative to
// this package's own directory (go test's working directory), so these
// tests exercise the actual recorded data rather than a copy of it.
var (
	messagesDir = filepath.Join("..", "..", "internal", "wire", "testdata", "messages")
	protocolDir = filepath.Join("..", "..", "internal", "engine", "testdata", "protocol")
)

func TestFixturesCommand(t *testing.T) {
	out := filepath.Join(t.TempDir(), "fixtures.gen.ts")
	stdout, _ := runOK(t, "fixtures", "-out", out, "-messages", messagesDir, "-protocol", protocolDir)
	if !strings.Contains(stdout, out) {
		t.Errorf("stdout = %q, want it to mention %s", stdout, out)
	}
	data, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	src := string(data)

	for _, want := range []string{
		"// Code generated by `ajayeb-gen fixtures`. DO NOT EDIT.",
		"import type { ServerMessage } from './index';",
		"import type { View } from './view.gen';",
		"export const fixtures = [",
		"] satisfies ServerMessage[];",
		"export const protocolFixtures = [",
		"] satisfies View[];",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("fixtures.gen.ts lacks %q", want)
		}
	}

	messageFiles, err := os.ReadDir(messagesDir)
	if err != nil {
		t.Fatal(err)
	}
	wantMessages := jsonFileCount(t, messageFiles)
	if n := strings.Count(src, `"t":`); n != wantMessages {
		t.Errorf(`fixtures.gen.ts has %d "t" fields, want %d (one per recorded message)`, n, wantMessages)
	}

	// Every View carries a top-level "schema" field, once for each viewer in
	// the protocol fixtures and once more for each recorded wire message
	// that happens to be a state frame (its own View is nested one level
	// in), so the total is both sources' counts added together.
	wantSchemas := 0
	protocolFiles, err := os.ReadDir(protocolDir)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range protocolFiles {
		if e.IsDir() || filepath.Ext(e.Name()) != ".json" {
			continue
		}
		b, err := os.ReadFile(filepath.Join(protocolDir, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		var f protocolFixtureFile
		if err := json.Unmarshal(b, &f); err != nil {
			t.Fatal(err)
		}
		wantSchemas += len(f.Viewers)
	}
	for _, e := range messageFiles {
		if e.IsDir() || filepath.Ext(e.Name()) != ".json" {
			continue
		}
		b, err := os.ReadFile(filepath.Join(messagesDir, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		var head struct {
			View *struct{} `json:"view"`
		}
		if err := json.Unmarshal(b, &head); err != nil {
			t.Fatal(err)
		}
		if head.View != nil {
			wantSchemas++
		}
	}
	if n := strings.Count(src, `"schema":`); n != wantSchemas {
		t.Errorf(`fixtures.gen.ts has %d "schema" fields, want %d (one per recorded view, plus one per state message)`, n, wantSchemas)
	}

	// The generated file is itself valid, balanced source: every opening
	// brace and bracket in the spliced-in JSON is matched (a crude but
	// effective check that indentBlock did not mangle anything).
	if o, c := strings.Count(src, "{"), strings.Count(src, "}"); o != c {
		t.Errorf("unbalanced braces: %d { vs %d }", o, c)
	}
	if o, c := strings.Count(src, "["), strings.Count(src, "]"); o != c {
		t.Errorf("unbalanced brackets: %d [ vs %d ]", o, c)
	}
}

func jsonFileCount(t *testing.T, entries []os.DirEntry) int {
	t.Helper()
	n := 0
	for _, e := range entries {
		if !e.IsDir() && filepath.Ext(e.Name()) == ".json" {
			n++
		}
	}
	return n
}

func TestFixturesCommandMissingDir(t *testing.T) {
	out := filepath.Join(t.TempDir(), "fixtures.gen.ts")
	var stdout, stderr bytes.Buffer
	code := run([]string{"fixtures", "-out", out, "-messages", filepath.Join(t.TempDir(), "nope"), "-protocol", protocolDir}, &stdout, &stderr)
	if code != 1 {
		t.Fatalf("run = %d, want 1; stderr: %s", code, stderr.String())
	}
	if !strings.Contains(stderr.String(), "reading recorded messages") {
		t.Errorf("stderr = %q", stderr.String())
	}
}

func TestFixturesCommandBadArgs(t *testing.T) {
	var stdout, stderr bytes.Buffer
	code := run([]string{"fixtures", "extra"}, &stdout, &stderr)
	if code != 2 {
		t.Fatalf("run = %d, want 2; stderr: %s", code, stderr.String())
	}
	if !strings.Contains(stderr.String(), `unexpected argument "extra"`) {
		t.Errorf("stderr = %q", stderr.String())
	}
}

func TestFixturesHelp(t *testing.T) {
	var stdout, stderr bytes.Buffer
	code := run([]string{"fixtures", "-help"}, &stdout, &stderr)
	if code != 0 {
		t.Fatalf("run = %d, want 0", code)
	}
	if !strings.Contains(stderr.String(), "-messages") || !strings.Contains(stderr.String(), "-protocol") {
		t.Errorf("stderr = %q", stderr.String())
	}
}

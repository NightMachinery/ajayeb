// This file writes the presentation catalog as a TypeScript module for the
// web client, web/src/lib/wire/catalog.gen.ts. It holds exactly the data of
// `ajayeb-gen catalog -format json` (the same jsonCatalog values, built by
// buildCatalog), typed and keyed by slug, plus catalogHash: the engine's own
// fingerprint of the catalog (engine.CatalogHash), which every View carries
// in its catalogHash field. A client whose module has another hash than the
// views it receives was built from other card data, and says so.
//
// Every item is one line of compact JSON, so the file stays small,
// diffs line by line when one card changes, and a test can read every entry
// back with encoding/json.

// defaultCatalogTSOut is relative to server/, like defaultFixturesOut.
const defaultCatalogTSOut = "../web/src/lib/wire/catalog.gen.ts"

// effectKindNames lists every effect kind's wire name in enum order,
// skipping the zero kind "none", which no effect uses.
func effectKindNames() []string {
	var out []string
	for k := catalog.EffectKind(1); ; k++ {
		name := k.String()
		if strings.HasPrefix(name, "effect#") {
			return out
		}
		out = append(out, name)
	}
}

// tsUnion writes a union of string literal types, such as 'a' | 'b'.
func tsUnion(names []string) string {
	quoted := make([]string, len(names))
	for i, n := range names {
		quoted[i] = "'" + n + "'"
	}
	return strings.Join(quoted, " | ")
}

// slugList writes a readonly tuple of slugs, one per line.
func slugList(b *strings.Builder, name string, slugs []string) {
	fmt.Fprintf(b, "export const %s = [\n", name)
	for _, s := range slugs {
		fmt.Fprintf(b, "  '%s',\n", s)
	}
	b.WriteString("] as const;\n")
}

// entries writes one `'slug': {json},` line per item.
func entries[T any](b *strings.Builder, items []T, slug func(T) string) error {
	for _, it := range items {
		data, err := json.Marshal(it)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "  '%s': %s,\n", slug(it), data)
	}
	return nil
}

// catalogTS renders catalog.gen.ts.
func catalogTS() ([]byte, error) {
	cat := buildCatalog()
	cardSlugs := make([]string, len(cat.Cards))
	for i, c := range cat.Cards {
		cardSlugs[i] = c.Slug
	}
	wonderSlugs := make([]string, len(cat.Wonders))
	for i, w := range cat.Wonders {
		wonderSlugs[i] = w.Slug
	}
	tokenSlugs := make([]string, len(cat.Tokens))
	for i, t := range cat.Tokens {
		tokenSlugs[i] = t.Slug
	}
	for _, s := range append(append(append([]string{}, cardSlugs...), wonderSlugs...), tokenSlugs...) {
		// Slugs are kebab-case; anything else would need escaping in the
		// single-quoted literals below.
		if strings.ContainsAny(s, `'"\`+"\n") {
			return nil, fmt.Errorf("slug %q cannot be written as a TypeScript literal", s)
		}
	}

	var b strings.Builder
	b.WriteString(`// Code generated by ajayeb-gen. DO NOT EDIT.
//
// The presentation catalog: every building, wonder and progress token with
// the data a client shows (ids, names, colour, age, back, printed cost,
// declarative effects and chains), keyed by slug. It is presentation data,
// not rules: the server decides what is legal and what everything costs.
// The same data is ` + "`ajayeb-gen catalog -format json`" + `.
//
// catalogHash is the engine's fingerprint of this data (engine.CatalogHash).
// Every View carries the server's own in View.catalogHash; a client whose
// catalogHash differs was built from other card data and is stale.
import type { Back, Chain, Color, Resource, ScienceSymbol } from './view.gen';

`)
	fmt.Fprintf(&b, "export const catalogHash = '%s';\n", engine.CatalogHash())
	fmt.Fprintf(&b, "export const catalogSchema = %d;\n\n", jsonSchema)

	b.WriteString("/** An effect's kind: what it does. The other fields of CatalogEffect appear only when the kind uses them. */\n")
	fmt.Fprintf(&b, "export type EffectKind = %s;\n", tsUnion(effectKindNames()))
	b.WriteString("/** Whose city a per-card, per-wonder or per-coins effect counts: the owner's, or whichever has the most. */\n")
	b.WriteString("export type EffectScope = 'self' | 'max';\n")
	b.WriteString("/** What a discount token applies to. */\n")
	b.WriteString("export type DiscountTarget = 'blue' | 'wonder';\n\n")

	b.WriteString(`/** A printed cost: coins paid to the bank and resource units. */
export interface CatalogCost {
  readonly coins: number;
  readonly wood: number;
  readonly clay: number;
  readonly stone: number;
  readonly glass: number;
  readonly papyrus: number;
}

/**
 * One printed effect. n is the kind's count (units, shields, points or
 * coins), except for points-per-coins, where it is the number of coins that
 * make one point.
 */
export interface CatalogEffect {
  readonly kind: EffectKind;
  readonly n?: number;
  readonly resource?: Resource;
  readonly resources?: readonly Resource[];
  readonly colors?: readonly Color[];
  readonly symbol?: ScienceSymbol;
  readonly scope?: EffectScope;
  readonly target?: DiscountTarget;
}

/** A building. chainIn and chainFrom make it free; chainOut and chainTo are what it makes free. */
export interface CatalogCard {
  readonly id: number;
  readonly slug: CardSlug;
  readonly name: string;
  readonly altNames: readonly string[];
  readonly age: 1 | 2 | 3;
  readonly back: Back;
  readonly color: Color;
  readonly cost: CatalogCost;
  readonly effects: readonly CatalogEffect[];
  readonly chainIn?: Chain;
  readonly chainFrom?: CardSlug;
  readonly chainOut?: Chain;
  readonly chainTo?: CardSlug;
}

/** A wonder. */
export interface CatalogWonder {
  readonly id: number;
  readonly slug: WonderSlug;
  readonly name: string;
  readonly cost: CatalogCost;
  readonly effects: readonly CatalogEffect[];
}

/** A progress token. */
export interface CatalogToken {
  readonly id: number;
  readonly slug: TokenSlug;
  readonly name: string;
  readonly effects: readonly CatalogEffect[];
}

`)
	b.WriteString("/** Every building's slug, in id order. */\n")
	slugList(&b, "cardSlugs", cardSlugs)
	b.WriteString("export type CardSlug = (typeof cardSlugs)[number];\n\n")
	b.WriteString("/** Every wonder's slug, in id order. */\n")
	slugList(&b, "wonderSlugs", wonderSlugs)
	b.WriteString("export type WonderSlug = (typeof wonderSlugs)[number];\n\n")
	b.WriteString("/** Every progress token's slug, in id order. */\n")
	slugList(&b, "tokenSlugs", tokenSlugs)
	b.WriteString("export type TokenSlug = (typeof tokenSlugs)[number];\n\n")

	b.WriteString("export const cards: { readonly [S in CardSlug]: CatalogCard } = {\n")
	if err := entries(&b, cat.Cards, func(c jsonCard) string { return c.Slug }); err != nil {
		return nil, err
	}
	b.WriteString("};\n\n")
	b.WriteString("export const wonders: { readonly [S in WonderSlug]: CatalogWonder } = {\n")
	if err := entries(&b, cat.Wonders, func(w jsonWonder) string { return w.Slug }); err != nil {
		return nil, err
	}
	b.WriteString("};\n\n")
	b.WriteString("export const tokens: { readonly [S in TokenSlug]: CatalogToken } = {\n")
	if err := entries(&b, cat.Tokens, func(t jsonToken) string { return t.Slug }); err != nil {
		return nil, err
	}
	b.WriteString("};\n")
	return []byte(b.String()), nil
}

// writeCatalogTS writes catalog.gen.ts to out, creating its directory, and
// leaves an identical file untouched (so its modification time does not
// change on every make gen).
func writeCatalogTS(out string) error {
	data, err := catalogTS()
	if err != nil {
		return err
	}
	return writeIfChanged(out, data)
}

// writeIfChanged writes data to out, creating its directory, and leaves a
// file that already holds exactly data untouched.
func writeIfChanged(out string, data []byte) error {
	if old, err := os.ReadFile(out); err == nil && bytes.Equal(old, data) {
		return nil
	}
	if dir := filepath.Dir(out); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	return os.WriteFile(out, data, 0o644)
}

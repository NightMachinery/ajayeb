#!/usr/bin/env python3
"""Derive mono AAC cues and their hashed URL index from approved originals.

Run through tools/heavy.py --kind build. Requires ffmpeg, no Python packages.
The sound sources and CC0 provenance are in art/originals/sound/sources.json.
"""
from array import array
import hashlib
import json
import math
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
RATE = 48000
FFMPEG = shutil.which("ffmpeg")
if not FFMPEG:
    raise SystemExit("ffmpeg is required")


def run(*args, data=None):
    return subprocess.run([FFMPEG, "-v", "error", "-nostdin", *args],
                          input=data, capture_output=True, check=True).stdout


def decode(path):
    samples = array("f")
    samples.frombytes(run("-i", str(path), "-ac", "1", "-ar", str(RATE),
                         "-f", "f32le", "-"))
    if sys.byteorder != "little":
        samples.byteswap()
    return samples


def loudest_window(samples, width, square=True):
    width = min(width, len(samples))
    values = [v * v if square else abs(v) for v in samples]
    total = sum(values[:width])
    best, index = total, 0
    for i in range(width, len(values)):
        total += values[i] - values[i - width]
        if total > best:
            best, index = total, i - width + 1
    return best / width, index


def prepare(samples, cue):
    peak = max(map(abs, samples))
    if not peak:
        raise ValueError(f"{cue}: silent original")
    threshold = peak * 10 ** (-45 / 20)
    start = next(i for i, v in enumerate(samples) if abs(v) > threshold)
    end = next(i for i in range(len(samples) - 1, -1, -1) if abs(samples[i]) > threshold)
    samples = samples[max(0, start - 48):end + 1]
    limit = int({"fanfare": 3, "defeat": 3, "ageStart": 2}.get(cue, 1.5) * RATE)
    _, window = loudest_window(samples, 2400, square=False)
    center = window + 1200
    if len(samples) > limit and center > limit - 9600:
        samples = samples[max(0, center - int(0.3 * limit)):]
        for i in range(min(480, len(samples))):
            samples[i] *= i / 479
    fade = int((0.06 if len(samples) > limit else 0.008) * RATE)
    samples = samples[:limit]
    if len(samples) > 2 * fade:
        for i in range(fade):
            samples[-fade + i] *= 1 - i / (fade - 1)
    power, _ = loudest_window(samples, 14400)
    gain = min(0.1 / max(math.sqrt(power), 1e-6),
               10 ** (-1 / 20) / max(map(abs, samples)))
    return array("f", (v * gain for v in samples))


def main():
    sources = json.loads((ROOT / "art/originals/sound/sources.json").read_text())
    dest = ROOT / "web/static/sfx"
    dest.mkdir(parents=True, exist_ok=True)
    index = ["// Generated by tools/sound/process.py. Do not edit by hand.",
             "export const SOUND_FILES = {"]
    total = 0
    for cue, source in sources.items():
        samples = prepare(decode(ROOT / source["original"]), cue)
        if sys.byteorder != "little":
            samples.byteswap()
        out = dest / f"{cue}.m4a"
        run("-y", "-f", "f32le", "-ar", str(RATE), "-ac", "1", "-i", "-",
            "-map_metadata", "-1", "-c:a", "aac", "-profile:a", "aac_low",
            "-b:a", "64k", "-movflags", "+faststart", "-fflags", "+bitexact",
            str(out), data=samples.tobytes())
        digest = hashlib.sha256(out.read_bytes()).hexdigest()[:12]
        gain = {"slide": 0.65, "yourTurn": 0.35}.get(cue, 1)
        index.append(f"  {cue}: {{ url: '/sfx/{cue}.m4a?v={digest}', gain: {gain} }},")
        total += out.stat().st_size
        decoded = decode(out)
        power, _ = loudest_window(decoded, 14400)
        print(f"{cue}: {len(decoded)/RATE:.3f}s, peak "
              f"{20*math.log10(max(map(abs, decoded))):.2f} dBFS, "
              f"loudest 300ms {10*math.log10(power):.2f} dBFS RMS, {out.stat().st_size} bytes")
    index[-1] = index[-1].rstrip(",")
    index.extend(["} as const;", ""])
    (ROOT / "web/src/lib/fx/sounds.gen.ts").write_text("\n".join(index))
    print(f"Total: {total} bytes")


if __name__ == "__main__":
    main()
